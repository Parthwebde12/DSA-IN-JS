// Length
let a = "Parth";

console.log(a.length);

// slice(start, end)
console.log(a.slice(1, a.length));

// substring(start, end)
console.log(a.substring(2, 4));

// toUpperCase
console.log(a.toUpperCase());

// toLowerCase
console.log(a.toLowerCase());

// concat
console.log(a.concat(" ", "is", " ", "learning"));

// trim
console.log(a.trim());

// indexOf
console.log(a.indexOf("a"));

// lastIndexOf
console.log(a.lastIndexOf("a"));

//includes
console.log(a.includes("r"))

//startwith
console.log(a.startsWith("r"));

//endswith
console.log(a.endsWith("h"));

//replace
console.log(a.replace("P","h"))

//replaceall
console.log(a.replaceAll("P","4"))

//split: returns in array
console.log(a.split())


//CharAt
console.log(a.charAt(3))
console.log(a.charCodeAt(3))